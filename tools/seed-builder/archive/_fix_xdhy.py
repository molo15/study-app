def get_note(kname):
    for key, note in NOTES.items():
        if key in kname:
            return note
    return '本题考查现代汉语基础知识。'

# 1) 去重（跨知识点保留第一条）
seen = {}
for k in KP['knowledge']:
    keep = []
    for q in k.get('basicQuestions', []):
        ns = norm(q['stem'])
        if ns in seen:
            continue
        seen[ns] = k['name']
        keep.append(q)
    k['basicQuestions'] = keep

# 2) 补全空解析
filled = 0
for k in KP['knowledge']:
    for q in k.get('basicQuestions', []):
        if not q.get('explanation'):
            note = get_note(k['name'])
            ans = q.get('answer', '')
            q['explanation'] = f"本题考查“{k['name']}”知识点。{note}本题答案为“{ans}”。"
            filled += 1

