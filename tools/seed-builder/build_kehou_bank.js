const S_ANS = '作答格式：①要点分条 ②每条一句话说清';

let seq = 0;
const qs = [];

function push(q) {
  seq += 1;
  q.id = `${BANK}:k_${String(seq).padStart(6, '0')}`;
  q.tags = ['课后题', ...(q.tags || [])];
  if (!q.difficulty) q.difficulty = 'medium';
  qs.push(q);
}

// helper: single choice
function sc(doc, idx, chapter, stem, opts, ansKey, exp, tags, diff) {
  const keys = ['A', 'B', 'C', 'D'];
  push({
    type: 'single_choice',
    stem,
    options: opts.map((t, i) => ({ key: keys[i], text: t })),
    answer: ansKey,
    explanation: exp,
    chapter,
    tags,
    difficulty: diff,
    source: { blockId: B[doc][idx], docPath: DOC[doc].path },
  });
}
// helper: multi choice
function mc(doc, idx, chapter, stem, opts, ansKeys, exp, tags, diff) {
  const keys = ['A', 'B', 'C', 'D', 'E', 'F'];
  push({
    type: 'multi_choice',
    stem,
    options: opts.map((t, i) => ({ key: keys[i], text: t })),
    answer: ansKeys,
    explanation: exp,
    chapter,
    tags,
    difficulty: diff,
    source: { blockId: B[doc][idx], docPath: DOC[doc].path },
  });
}
// helper: blank
function bl(doc, idx, chapter, stem, answers, exp, tags, diff) {
  push({
    type: 'blank',
    stem,
    answer: Array.isArray(answers) ? answers : [answers],
    explanation: exp,
    chapter,
    tags,
    difficulty: diff,
    source: { blockId: B[doc][idx], docPath: DOC[doc].path },
  });
}
// helper: true/false
function tf(doc, idx, chapter, stem, correct, exp, tags, diff) {
  push({
    type: 'true_false',
    stem,
    answer: correct ? '正确' : '错误',
    explanation: exp,
    chapter,
    tags,
    difficulty: diff,
    source: { blockId: B[doc][idx], docPath: DOC[doc].path },
  });
}
// helper: short answer
function sa(doc, idx, chapter, stem, refAns, exp, tags, diff) {
  push({
    type: 'short_answer',
    stem,
    answer: refAns,
    explanation: exp,
    answerFormat: S_ANS,
    chapter,
    tags,
    difficulty: diff,
    source: { blockId: B[doc][idx], docPath: DOC[doc].path },
  });
}

