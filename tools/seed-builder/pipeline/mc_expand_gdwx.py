        for n in names:
            if n == 'manifest.json':
                zout.writestr(n, json.dumps(manifest, ensure_ascii=False, indent=1))
            elif n in chap_data and n.startswith('questions/测试-'):
                zout.writestr(n, json.dumps(chap_data[n], ensure_ascii=False, indent=1))
